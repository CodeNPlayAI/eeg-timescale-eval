def _validate_self_run_metadata(self_dir: Path) -> tuple[Path, Path]:
    run_root = self_dir.parent
    run_config = run_root / "run_config.json"
    source_validation = self_dir / "validation_report.json"
    if not run_config.is_file():
        raise FileNotFoundError(
            f"Aligned self-EEG provenance cannot be verified without {run_config}"
        )
    if not source_validation.is_file():
        raise FileNotFoundError(
            f"Aligned self-EEG provenance cannot be verified without {source_validation}"
        )

    config = json.loads(run_config.read_text(encoding="utf-8"))
    if config.get("dataset_label") != "self_eeg" or config.get("subject_id") != "self_eeg":
        raise ValueError("Self-EEG run_config.json does not identify the canonical self_eeg source")
    if [int(seed) for seed in config.get("seeds", [])] != EXPECTED_SEEDS:
        raise ValueError("Self-EEG run_config.json must list exactly seeds 0-19 in order")
    if config.get("run_e1_e2") is not True:
        raise ValueError("Self-EEG run_config.json does not confirm E1/E2 execution")
    if set(config.get("channels", [])) != {"F7", "F8"}:
        raise ValueError("Self-EEG run_config.json must specify F7 and F8")
    for key in ("diffusion_only", "add_residual_diffusion"):
        if key not in config:
            raise ValueError(f"Self-EEG run_config.json is missing {key}")
        locked = config[key]
        observed = (
            int(locked["T"]),
            int(locked["optimization_updates"]),
            int(locked["batch_size"]),
        )
        if observed != (1000, 800, 8):
            raise ValueError(f"Unaligned self-EEG DDPM configuration for {key}: {observed}")

    validation = json.loads(source_validation.read_text(encoding="utf-8"))
    expected_validation = {
        "expected_subjects": 1,
        "expected_seeds_per_subject": 20,
        "found_subjects": 1,
        "found_subject_seed_pairs": 20,
        "e2_rows": 20,
    }
    for key, expected_value in expected_validation.items():
        if int(validation.get(key, -1)) != expected_value:
            raise ValueError(
                f"Self-EEG validation_report.json has {key}={validation.get(key)!r}; "
                f"expected {expected_value}"
            )
    if validation.get("status") != "complete" or validation.get("problems") != []:
        raise ValueError("Self-EEG validation_report.json does not report a complete, problem-free run")
    for key in ("diffusion_only", "add_residual_diffusion"):
        observed = validation.get("configuration", {}).get(key, {})
        triple = (
            int(observed.get("T", -1)),
            int(observed.get("optimization_updates", -1)),
            int(observed.get("batch_size", -1)),
        )
        if triple != (1000, 800, 8):
            raise ValueError(f"Self-EEG validation report is not aligned for {key}: {triple}")
    return run_config, source_validation


def validate_self(
    self_dir: Path,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, Path, Path, Path, Path, Path]:
    metrics_path, e1_path, e2_path = find_self_source_paths(self_dir)
    run_config, source_validation = _validate_self_run_metadata(self_dir)
    metrics = pd.read_csv(metrics_path)
    e1 = pd.read_csv(e1_path)
    e2 = pd.read_csv(e2_path)
    if "subject" in metrics.columns and set(metrics["subject"].astype(str)) != {"self_eeg"}:
        raise ValueError("Self-EEG metrics source contains an unexpected subject")
    if {"condition", "metric", "metric_label", "real_value", "absolute_error"}.issubset(metrics.columns):
        metrics = metrics.loc[metrics["condition"] != "Real"].rename(
            columns={
                "metric": "metric_key",
                "metric_label": "Metric",
                "condition": "model",
                "real_value": "real",
                "absolute_error": "abs_error",
            }
        )
        metrics = metrics[["seed", "metric_key", "Metric", "model", "real", "value", "abs_error"]]
    required_metrics = {"seed", "metric_key", "Metric", "model", "real", "value", "abs_error"}
    missing_metrics = required_metrics - set(metrics.columns)
    if missing_metrics:
        raise ValueError(f"Missing self-EEG metrics columns: {sorted(missing_metrics)}")
    metrics = metrics[list(required_metrics)].copy()
    metrics["seed"] = metrics["seed"].astype(int)
    if len(metrics) != 20 * 5 * 3:
        raise ValueError(f"Expected 300 self-EEG metric rows, found {len(metrics)}")
    if sorted(metrics["seed"].unique().tolist()) != EXPECTED_SEEDS:
        raise ValueError("Self-EEG result does not contain seeds 0-19")
    if set(metrics["model"]) != set(CORE_MODELS):
        raise ValueError("Self-EEG result does not contain the locked core-three model set")
    if set(metrics["metric_key"]) != set(METRICS):
        raise ValueError("Self-EEG metric set differs from the locked five metrics")
    if metrics.duplicated(["seed", "metric_key", "model"]).any():
        raise ValueError("Duplicate self-EEG seed-metric-model rows found")
    if not np.isfinite(metrics[["real", "value", "abs_error"]].astype(float).to_numpy()).all():
        raise ValueError("Non-finite self-EEG metric value found")
    expected_abs = (metrics["value"] - metrics["real"]).abs()
    if not np.allclose(expected_abs, metrics["abs_error"], rtol=0, atol=1e-12):
        raise ValueError("Self-EEG abs_error column is inconsistent with value and real")

    if "subject" in e1.columns and set(e1["subject"].astype(str)) != {"self_eeg"}:
        raise ValueError("E1 source contains an unexpected subject")
    if {"series", "metric_label", "value"}.issubset(e1.columns):
        if e1.duplicated(["subject", "seed", "series", "metric_label"]).any():
            raise ValueError("Duplicate long-form E1 rows found")
        e1 = (
            e1.pivot(index=["subject", "seed", "series"], columns="metric_label", values="value")
            .reset_index()
            .rename_axis(columns=None)
        )
        for expected_column in ("ACF@0.1s", "ACF@0.5s", "ACF@1.0s"):
            if expected_column not in e1.columns:
                raise ValueError(f"Missing E1 metric column: {expected_column}")
    if len(e1) != 20 * 3:
        raise ValueError(f"Expected 60 E1 rows, found {len(e1)}")
    e1["seed"] = e1["seed"].astype(int)
    if sorted(e1["seed"].unique().tolist()) != EXPECTED_SEEDS:
        raise ValueError("E1 result does not contain seeds 0-19")
    if set(e1["series"]) != {"residual_true", "residual_hat", "residual_hat_stdmatched"}:
        raise ValueError(f"Unexpected E1 series: {sorted(e1['series'].unique().tolist())}")
    if e1.duplicated(["seed", "series"]).any():
        raise ValueError("Duplicate E1 seed-series rows found")
    e1_value_columns = ["ACF@0.1s", "ACF@0.5s", "ACF@1.0s"]
    if not np.isfinite(e1[e1_value_columns].astype(float).to_numpy()).all():
        raise ValueError("Non-finite E1 value found")

    required_e2 = {
        "seed", "base_csv", "residual_csv", "fs", "win_s", "hop_s",
        "XCF_at_0.1s_mean", "XCF_at_0.5s_mean", "XCF_at_1.0s_mean",
    }
    missing_e2 = required_e2 - set(e2.columns)
    if missing_e2:
        raise ValueError(f"Missing E2 per-seed columns: {sorted(missing_e2)}")
    e2["seed"] = e2["seed"].astype(int)
    if len(e2) != 20 or sorted(e2["seed"].unique().tolist()) != EXPECTED_SEEDS:
        raise ValueError("E2 source must contain exactly one row for each seed 0-19")
    if e2.duplicated(["seed"]).any():
        raise ValueError("Duplicate E2 seed rows found")
    if not np.isfinite(e2[[f"XCF_at_{lag}_mean" for lag in E2_LAGS]].astype(float).to_numpy()).all():
        raise ValueError("Non-finite E2 XCF value found")
    if not np.allclose(e2["fs"].astype(float), 256.0, rtol=0.0, atol=0.0):
        raise ValueError("E2 source must use fs=256")
    if not np.allclose(e2["win_s"].astype(float), 10.0, rtol=0.0, atol=0.0):
        raise ValueError("E2 source must use 10-s windows")
    if not np.allclose(e2["hop_s"].astype(float), 5.0, rtol=0.0, atol=0.0):
        raise ValueError("E2 source must use 5-s hops")

    run_name = self_dir.parent.name
    for record in e2.itertuples(index=False):
        seed = int(record.seed)
        base_text = str(record.base_csv)
        residual_text = str(record.residual_csv)
        seed_pattern = re.compile(rf"(?:^|[/\\])seed{seed}(?:[/\\]|$)")
        if run_name not in Path(base_text).parts or run_name not in Path(residual_text).parts:
            raise ValueError(f"E2 seed {seed} does not reference the aligned self-EEG run root")
        if not seed_pattern.search(base_text) or not seed_pattern.search(residual_text):
            raise ValueError(f"E2 seed {seed} provenance paths point to a different seed")
        if "nmm_base_aligned" not in Path(base_text).name:
            raise ValueError(f"E2 seed {seed} base provenance is not the aligned NMM component")
        if "residual_hat_stdmatched" not in Path(residual_text).name:
            raise ValueError(f"E2 seed {seed} residual provenance is not std-matched r_hat")

    return (
        metrics,
        e1,
        e2,
        metrics_path,
        e1_path,
        e2_path,
        run_config,
        source_validation,
    )


def round_half_away_from_zero(value: float, decimals: int = 3) -> float:
    factor = 10**decimals
    return math.copysign(math.floor(abs(value) * factor + 0.5) / factor, value)


def self_matrix(metrics: pd.DataFrame, seed: int) -> tuple[np.ndarray, np.ndarray, pd.DataFrame]:
    seed_df = metrics.loc[metrics["seed"] == seed].copy()
    seed_df["relative_error"] = seed_df["abs_error"] / seed_df["real"].abs()
    indexed = seed_df.set_index(["metric_key", "model"])
    relative = np.zeros((len(METRICS), 1 + len(CORE_MODELS)), dtype=float)
    raw = np.zeros_like(relative)
    for i, metric in enumerate(METRICS):
        raw[i, 0] = float(indexed.loc[(metric, "NMM-only"), "real"])
        for j, model in enumerate(CORE_MODELS, start=1):
            relative[i, j] = float(indexed.loc[(metric, model), "relative_error"])
            raw[i, j] = float(indexed.loc[(metric, model), "value"])
    return relative, raw, seed_df


def draw_self_heatmap(
    ax: plt.Axes,
    relative: np.ndarray,
    raw: np.ndarray,
    *,
    title: str | None,
    show_ylabels: bool,
    annotation_fontsize: float,
) -> mpl.image.AxesImage:
    columns = ["Real", *CORE_MODELS]
    im = ax.imshow(relative, cmap="viridis", vmin=0.0, vmax=0.40, aspect="auto", interpolation="nearest")
    ax.set_xticks(range(len(columns)), columns, rotation=25, ha="right")
    ax.set_yticks(range(len(METRICS)))
    if show_ylabels:
        ax.set_yticklabels([METRIC_FIG_LABEL[m] for m in METRICS])
    else:
        ax.tick_params(axis="y", labelleft=False)
    ax.tick_params(length=0)
    for i in range(relative.shape[0]):
        winner = 1 + int(np.argmin(relative[i, 1:]))
        ax.add_patch(
            Rectangle(
                (winner - 0.5, i - 0.5),
                1,
                1,
                fill=False,
                edgecolor="white",
                linewidth=2.3,
            )
        )
        for j in range(relative.shape[1]):
            error = relative[i, j]
            metric_value = round_half_away_from_zero(raw[i, j], 3)
            annotation = f"{metric_value:.3f}" if j == 0 else f"{metric_value:.3f}\n({error * 100.0:.1f}%)"
            rgba = im.cmap(im.norm(error))
            luminance = 0.2126 * rgba[0] + 0.7152 * rgba[1] + 0.0722 * rgba[2]
            color = "black" if luminance > 0.56 else "white"
            ax.text(
                j,
                i,
                annotation,
                ha="center",
                va="center",
                color=color,
                fontsize=annotation_fontsize,
                fontweight="normal",
            )
    if title:
        ax.set_title(title, loc="left", fontweight="bold", pad=8)
    for spine in ax.spines.values():
        spine.set_linewidth(0.8)
    return im


