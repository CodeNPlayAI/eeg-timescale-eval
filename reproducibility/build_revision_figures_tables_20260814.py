def _first_existing(parent: Path, names: list[str], label: str) -> Path:
    matches = [parent / name for name in names if (parent / name).is_file()]
    if len(matches) != 1:
        raise FileNotFoundError(
            f"Expected exactly one {label} under {parent}; found: "
            f"{[str(path) for path in matches]}"
        )
    return matches[0]


def _normalize_openneuro_seed_rows(raw: pd.DataFrame, path: Path) -> pd.DataFrame:
    normalized = raw.copy()
    if "metric_key" in normalized.columns and "metric" not in normalized.columns:
        normalized = normalized.rename(columns={"metric_key": "metric"})
    if "abs_error" in normalized.columns and "absolute_error" not in normalized.columns:
        normalized = normalized.rename(columns={"abs_error": "absolute_error"})
    required = {"subject", "seed", "metric", "model", "absolute_error"}
    missing = required - set(normalized.columns)
    if missing:
        raise ValueError(f"Missing OpenNeuro seed-level columns in {path}: {sorted(missing)}")
    normalized = normalized.loc[normalized["model"].isin(EXTENDED_MODELS)].copy()
    normalized["seed"] = normalized["seed"].astype(int)
    normalized["absolute_error"] = normalized["absolute_error"].astype(float)
    if len(normalized) != 30 * 20 * 5 * 4:
        raise ValueError(
            f"Expected 12,000 OpenNeuro subject-seed-model-metric rows in {path}, "
            f"found {len(normalized)}"
        )
    if set(normalized["subject"].astype(str)) != set(SUBJECTS):
        raise ValueError("OpenNeuro seed-level subject set differs from the locked 30-subject cohort")
    if set(normalized["seed"]) != set(EXPECTED_SEEDS):
        raise ValueError("OpenNeuro seed-level data do not contain exactly seeds 0-19")
    if set(normalized["model"].astype(str)) != set(EXTENDED_MODELS):
        raise ValueError("OpenNeuro seed-level data do not contain the required four models")
    if set(normalized["metric"].astype(str)) != set(METRICS):
        raise ValueError("OpenNeuro seed-level metric set differs from the required five metrics")
    if normalized.duplicated(["subject", "seed", "metric", "model"]).any():
        raise ValueError("Duplicate OpenNeuro subject-seed-model-metric rows found")
    cell_sizes = normalized.groupby(["subject", "metric", "model"])["seed"].nunique()
    if not cell_sizes.eq(20).all():
        raise ValueError("Every OpenNeuro subject-metric-model cell must contain exactly 20 seeds")
    if not np.isfinite(normalized["absolute_error"]).all():
        raise ValueError("Non-finite OpenNeuro absolute error found")
    if {"real", "value"}.issubset(normalized.columns):
        recomputed = (normalized["value"].astype(float) - normalized["real"].astype(float)).abs()
        if not np.allclose(recomputed, normalized["absolute_error"], rtol=0.0, atol=1e-12):
            raise ValueError("OpenNeuro absolute_error is inconsistent with value and real")
    return normalized


def validate_openneuro(
    open_dir: Path,
    explicit_seed_path: Path | None = None,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame, Path]:
    if not open_dir.is_dir():
        raise FileNotFoundError(f"OpenNeuro summary directory not found: {open_dir}")
    table5_path = open_dir / "table5_openneuro_subject_bootstrap_absolute.csv"
    winners_path = open_dir / "subject_level_winners_extended4.csv"
    counts_path = open_dir / "winner_counts.csv"
    phase_path = open_dir / "phase_summary.csv"
    for path in (table5_path, winners_path, counts_path, phase_path):
        if not path.is_file():
            raise FileNotFoundError(f"Required OpenNeuro summary missing: {path}")
    if explicit_seed_path is not None:
        seed_path = explicit_seed_path.resolve()
        if not seed_path.is_file():
            raise FileNotFoundError(f"OpenNeuro seed-level source not found: {seed_path}")
    else:
        seed_path = _first_existing(
            open_dir,
            [
                "OpenNeuro_all_errors_by_subject_seed_model_metric.csv",
                "all_errors_by_subject_seed_model_metric.csv",
                "all_errors_by_subject_seed_metric_model.csv",
            ],
            "OpenNeuro seed-level absolute-error source",
        )

    table5 = pd.read_csv(table5_path)
    winners = pd.read_csv(winners_path)
    counts = pd.read_csv(counts_path)
    phase = pd.read_csv(phase_path)
    seed_rows = _normalize_openneuro_seed_rows(pd.read_csv(seed_path), seed_path)

    if len(table5) != 20:
        raise ValueError(f"Expected 20 Table 5 rows, found {len(table5)}")
    if set(table5["model"]) != set(EXTENDED_MODELS):
        raise ValueError("Unexpected Table 5 model set")
    if set(table5["metric"]) != set(METRICS):
        raise ValueError("Unexpected Table 5 metric set")
    if not table5["n_subjects"].eq(30).all():
        raise ValueError("Table 5 does not consistently use N=30")
    if not table5["bootstrap_resamples"].eq(100000).all():
        raise ValueError("Table 5 bootstrap count differs from 100,000")
    if not table5["bootstrap_rng_seed"].eq(20260810).all():
        raise ValueError("Table 5 bootstrap seed differs from 20260810")

    if len(winners) != 150:
        raise ValueError(f"Expected 150 subject-metric winners, found {len(winners)}")
    if set(winners["subject"]) != set(SUBJECTS):
        raise ValueError("OpenNeuro subject set or identifiers differ from the locked cohort")
    if not winners["tie_cardinality"].eq(1).all():
        raise ValueError("Exact subject-metric tie found in final winner table")

    subject_means = (
        seed_rows.groupby(["subject", "metric", "model"], as_index=False)["absolute_error"]
        .mean()
    )
    if len(subject_means) != 30 * 5 * 4:
        raise ValueError("OpenNeuro two-stage aggregation did not yield 600 subject-metric-model rows")
    table5_indexed = table5.set_index(["metric", "model"])
    for (metric, model), group in subject_means.groupby(["metric", "model"]):
        values = group["absolute_error"].to_numpy(dtype=float)
        record = table5_indexed.loc[(metric, model)]
        checks = {
            "mean": float(np.mean(values)),
            "sd": float(np.std(values, ddof=1)),
            "median": float(np.median(values)),
        }
        for column, expected_value in checks.items():
            if not np.isclose(float(record[column]), expected_value, rtol=0.0, atol=1e-12):
                raise ValueError(
                    f"Table 5 {column} is inconsistent with subject-level aggregation "
                    f"for {metric}/{model}"
                )

    calculated_winners = (
        subject_means.sort_values(["subject", "metric", "absolute_error", "model"])
        .groupby(["subject", "metric"], as_index=False)
        .first()[["subject", "metric", "model"]]
        .rename(columns={"model": "calculated_winner"})
    )
    reported_winners = winners[["subject", "metric", "unique_winner"]].copy()
    winner_check = reported_winners.merge(
        calculated_winners, on=["subject", "metric"], how="outer", validate="one_to_one"
    )
    if not winner_check["unique_winner"].eq(winner_check["calculated_winner"]).all():
        raise ValueError("OpenNeuro participant-level winner table is inconsistent with 20-seed means")

    extended_rows = phase.loc[phase["phase"] == "Phase 3: extended 4"]
    if len(extended_rows) != 1:
        raise ValueError("Expected exactly one Phase 3 summary row")
    extended = extended_rows.iloc[0]
    expected = {
        "subject_tradeoff_count": 28,
        "subject_tradeoff_total": 30,
        "seed_tradeoff_count": 526,
        "seed_tradeoff_total": 600,
        "subject_metric_exact_tie_count": 0,
    }
    for key, value in expected.items():
        if int(extended[key]) != value:
            raise ValueError(f"Locked OpenNeuro check failed: {key}={extended[key]} != {value}")

    ext_counts = counts.loc[counts["phase"] == "Phase 3: extended 4"]
    observed_counts = dict(zip(ext_counts["model"], ext_counts["unique_winner_cells"]))
    if observed_counts != {"NMM-only": 11, "Diffusion-only": 31, "Add": 18, "WGAN-GP": 90}:
        raise ValueError(f"Locked winner-cell counts differ: {observed_counts}")

    return table5, winners, counts, phase, seed_path


