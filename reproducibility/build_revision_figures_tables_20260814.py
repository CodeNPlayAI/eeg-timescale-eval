def select_fig3_seeds(metrics: pd.DataFrame) -> tuple[list[tuple[str, int]], pd.DataFrame]:
    """Mechanically apply the original three-condition representative-case rules.

    Seed 0 is reserved for Fig. 2. Model-specific cases are selected first,
    followed by the median-like case. Lower seed number is the deterministic
    tie-breaker.
    """
    candidates = metrics.loc[metrics["seed"] != 0].copy()
    overall = candidates.groupby("seed", as_index=True)["abs_error"].mean()
    diffusion = (
        candidates.loc[candidates["model"] == "Diffusion-only"]
        .groupby("seed", as_index=True)["abs_error"]
        .mean()
    )
    long_lag = candidates.loc[
        candidates["metric_key"].isin(["acf_x_abs_0_5s", "acf_x_abs_1_0s"])
    ].pivot_table(index=["seed", "metric_key"], columns="model", values="abs_error")
    nmm_advantage = (
        (long_lag["Diffusion-only"] - long_lag["NMM-only"])
        .groupby("seed")
        .mean()
    )

    diffusion_seed = int(
        pd.DataFrame({"score": diffusion.to_numpy(), "seed": diffusion.index.to_numpy()})
        .sort_values(["score", "seed"], ascending=[True, True])
        .iloc[0]["seed"]
    )
    nmm_pool = nmm_advantage.drop(index=diffusion_seed, errors="ignore")
    nmm_seed = int(
        pd.DataFrame({"score": nmm_pool.to_numpy(), "seed": nmm_pool.index.to_numpy()})
        .sort_values(["score", "seed"], ascending=[False, True])
        .iloc[0]["seed"]
    )
    median_target = float(np.median(overall.to_numpy(dtype=float)))
    median_pool = overall.drop(index=[diffusion_seed, nmm_seed], errors="ignore")
    median_distance = (median_pool - median_target).abs()
    median_seed = int(
        pd.DataFrame({"distance": median_distance.to_numpy(), "seed": median_distance.index.to_numpy()})
        .sort_values(["distance", "seed"], ascending=[True, True])
        .iloc[0]["seed"]
    )

    score_rows = []
    for seed in sorted(int(value) for value in overall.index):
        score_rows.append(
            {
                "seed": seed,
                "overall_mean_absolute_error": float(overall.loc[seed]),
                "distance_from_candidate_median": float(abs(overall.loc[seed] - median_target)),
                "diffusion_only_mean_absolute_error": float(diffusion.loc[seed]),
                "nmm_long_lag_advantage": float(nmm_advantage.loc[seed]),
                "selected_case": (
                    "median-like" if seed == median_seed else
                    "diffusion-dominant" if seed == diffusion_seed else
                    "NMM-favorable" if seed == nmm_seed else ""
                ),
            }
        )
    scores = pd.DataFrame(score_rows)
    scores.attrs["median_target"] = median_target
    return [("a", median_seed), ("b", diffusion_seed), ("c", nmm_seed)], scores


