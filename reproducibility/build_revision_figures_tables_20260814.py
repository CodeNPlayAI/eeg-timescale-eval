def _e2_bootstrap_ci_mean(values: np.ndarray) -> tuple[float, float]:
    """Mirror the frozen E2 aggregation: percentile CI, B=10,000, RNG=42."""
    x = np.asarray(values, dtype=float)
    if x.shape != (20,) or not np.isfinite(x).all():
        raise ValueError("E2 bootstrap requires exactly 20 finite seed-level values")
    rng = np.random.default_rng(E2_BOOTSTRAP_RNG_SEED)
    indices = rng.integers(0, len(x), size=(E2_BOOTSTRAP_RESAMPLES, len(x)))
    means = x[indices].mean(axis=1)
    return float(np.quantile(means, 0.025)), float(np.quantile(means, 0.975))


def build_table3_e2(e2: pd.DataFrame, tables_dir: Path, source_dir: Path) -> None:
    """Build E2 Table 3 from aligned self-EEG seed-level XCF outputs."""
    e2.sort_values("seed").to_csv(source_dir / "Table3_E2_cross_term_all_seeds_source.csv", index=False)
    rows: list[list[object]] = []
    for lag in E2_LAGS:
        values = e2[f"XCF_at_{lag}_mean"].to_numpy(dtype=float)
        lower, upper = _e2_bootstrap_ci_mean(values)
        rows.append(
            [
                f"XCF @ {lag}",
                20,
                float(np.mean(values)),
                float(np.std(values, ddof=1)),
                lower,
                upper,
            ]
        )
    header = ["Metric", "N", "Mean", "SD", "95% CI lower", "95% CI upper"]
    write_csv(tables_dir / "Table3_E2_cross_term_20seeds.csv", header, rows)
    display_rows = [
        [row[0], row[1], f"{row[2]:.4f}", f"{row[3]:.4f}", f"{row[4]:.4f}", f"{row[5]:.4f}"]
        for row in rows
    ]
    write_markdown(tables_dir / "Table3_E2_cross_term_20seeds.md", header, display_rows)


